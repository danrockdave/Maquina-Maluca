GLYPH_W, GLYPH_H = 5, 7


def normalize(text):
    text = unicodedata.normalize('NFKD', text)
    return ''.join(ch for ch in text if not unicodedata.combining(ch)).upper()


def text_width(text, scale=1, spacing=1):
    n = len(normalize(text))
    if n == 0:
        return 0
    return n * (GLYPH_W + spacing) * scale - spacing * scale


def text_height(scale=1):
    return GLYPH_H * scale


def _fill_block(fb, x, y, size, color, clip):
    """A size x size block of set_pixel calls, written as one slice assignment."""
    x0, y0, x1, y1 = clip if clip is not None else (0, 0, fb.shape[0], fb.shape[1])
    xa, ya = max(x, x0), max(y, y0)
    xb, yb = min(x + size, x1), min(y + size, y1)
    if xa < xb and ya < yb:
        fb[xa:xb, ya:yb] = color


def draw_text(fb, x, y, text, color, scale=1, clip=None, spacing=1):
    """Draws text with its top-left corner at (x, y)."""
    x = int(x)
    y = int(y)
    for ch in normalize(text):
        rows = _GLYPHS.get(ch, _GLYPHS['?'])
        for row_i, row in enumerate(rows):
            for col_i, bit in enumerate(row):
                if bit == '1':
                    px = x + col_i * scale
                    py = y + row_i * scale
                    if scale == 1:
                        set_pixel(fb, px, py, color, clip)
                    else:
                        _fill_block(fb, px, py, scale, color, clip)
        x += (GLYPH_W + spacing) * scale


def draw_text_centered(fb, cx, y, text, color, scale=1, clip=None):
    draw_text(fb, cx - text_width(text, scale) // 2, y, text, color, scale, clip)
